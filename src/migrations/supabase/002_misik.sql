-- 등급별 뽑힐 가중치 (R 6 · SR 3 · SSR 1)
create table misik_grades (
  grade  text primary key check (grade in ('R', 'SR', 'SSR')),
  weight int not null check (weight between 1 and 100),
  stars  int not null check (stars between 1 and 5)
);

create table misik_menus (
  id         bigint generated by default as identity primary key,
  name       text not null unique check (char_length(name) between 1 and 30),
  grade      text not null references misik_grades (grade),
  created_at timestamptz not null default now()
);

-- 좋아요(1) · 싫어요(-1)를 누를 때마다 한 줄씩 쌓임
create table misik_votes (
  id         bigint generated by default as identity primary key,
  menu_id    bigint not null references misik_menus (id) on delete cascade,
  value      smallint not null check (value in (1, -1)),
  created_at timestamptz not null default now()
);

-- 뽑기 기록: 메뉴가 지워져도 기록은 남도록 이름 · 등급을 함께 저장
create table misik_draws (
  id        bigint generated by default as identity primary key,
  menu_id   bigint references misik_menus (id) on delete set null,
  menu_name text not null,
  grade     text not null check (grade in ('R', 'SR', 'SSR')),
  user_name text not null,
  drawn_at  timestamptz not null default now()
);

-- 메뉴별 좋아요 · 싫어요 수
create view misik_vote_counts with (security_invoker = true) as
  select menu_id,
         count(*) filter (where value = 1)::int as likes,
         count(*) filter (where value = -1)::int as dislikes
  from misik_votes
  group by menu_id;

-- RLS는 켜고 정책은 두지 않는다 → 서버 전용 키(Secret)를 가진 서버만 읽고 쓸 수 있음
alter table misik_grades enable row level security;
alter table misik_menus enable row level security;
alter table misik_votes enable row level security;
alter table misik_draws enable row level security;
